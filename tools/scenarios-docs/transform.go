package scenariosdocs

import (
	"bytes"
	"errors"
	"fmt"
	"regexp"
	"slices"
	"strings"
)

const (
	// repoSlug is the GitHub repository the documentation is generated from.
	repoSlug = "grafana/alloy-scenarios"

	// defaultBranch is the branch that scenario links point at. The links aren't
	// pinned to the generated commit, so a reader always lands on the current
	// scenario. A directory URL is used rather than a README URL because GitHub
	// renders the README on the directory page whatever the file is called, and
	// not every scenario has a README.md exactly.
	defaultBranch = "main"

	// scenariosMarker is the README heading that introduces the category tables.
	// Everything before it applies to every scenario.
	scenariosMarker = "## Scenarios"

	// endMarker is the README heading where imported content stops. Everything
	// from this line onwards (contributing guidance, license) stays on GitHub.
	endMarker = "## Contribute"

	// preambleSlug names the generated file holding the sections that apply to
	// every scenario. The scenarios landing page imports it.
	preambleSlug = "run-a-scenario"

	// preambleTitle describes the preamble in its front matter.
	preambleTitle = "Run a scenario"

	// headerFormat takes the page slug, the page title, the repository slug, and
	// the full commit SHA.
	headerFormat = "---\n" +
		"canonical: https://grafana.com/docs/alloy/latest/shared/scenarios/%s/\n" +
		"description: Shared content, Alloy scenarios, %s\n" +
		"headless: true\n" +
		"---\n" +
		"\n" +
		"<!--\n" +
		"This file is automatically generated by tools/scenarios-docs from\n" +
		"https://github.com/%s at commit %s.\n" +
		"Do not edit it directly. Run `task docs:scenarios-sync` instead.\n" +
		"-->\n" +
		"\n"

	// footerLine closes each category page. Its link is defined alongside the
	// scenario links at the bottom of the page.
	footerLine = "Refer to the [" + repoLabel + "][] repository for the full list of scenarios."

	// repoLabel is the reference-link label for the repository itself.
	repoLabel = "alloy-scenarios"

	// repoURL is the repository landing page.
	repoURL = "https://github.com/" + repoSlug
)

var (
	// linkRe matches inline links and images: [text](dest) and ![alt](dest).
	linkRe = regexp.MustCompile(`(!?)\[([^\]]*)\]\(([^)\s]+)\)`)
	// defRe matches reference-style link definitions: [label]: dest.
	defRe = regexp.MustCompile(`^\[([^\]]+)\]:\s*(\S+)(.*)$`)
	// schemeRe matches a URL scheme such as https: or mailto:.
	schemeRe = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9+.-]*:`)
	// shaRe matches a full, lowercase Git commit SHA.
	shaRe = regexp.MustCompile(`^[0-9a-f]{40}$`)
	// markerRe matches the comment that assigns a documentation slug to a README
	// category, for example "<!-- alloy-docs: slug=logs -->".
	markerRe = regexp.MustCompile(`^<!--\s*alloy-docs:\s*slug=([a-z0-9]+(?:-[a-z0-9]+)*)\s*-->$`)
	// looseMarkerRe matches anything that looks like an alloy-docs marker, so a
	// typo fails loudly instead of silently dropping a category.
	looseMarkerRe = regexp.MustCompile(`^<!--\s*alloy-docs\b`)
)

// Page is a generated shared documentation file.
type Page struct {
	// Slug names the file and the README category it came from.
	Slug string
	// Title describes the page in its front matter.
	Title string
	// Content is the complete file, including front matter.
	Content []byte
}

// Transform converts the alloy-scenarios README into the shared documentation
// files that the Alloy docs import: one preamble that applies to every
// scenario, and one scenario table per category.
//
// It is a pure function of its inputs so that the generated files are
// reproducible: the same README at the same commit always yields the same
// bytes. It fails, instead of guessing, when the README no longer has the
// structure the rules rely on.
//
// The rules are:
//
//   - Drop the leading HTML banner, the H1, and any repository-specific intro
//     before the first H2. The documentation pages supply titles and intros.
//   - Everything between the first H2 and "## Scenarios" becomes the preamble.
//   - Each category under "## Scenarios" must carry an alloy-docs slug marker,
//     and contributes its scenario table as its own file. The category heading
//     and prose stay in the README, because the hand-written documentation page
//     introduces the table.
//   - Drop everything from the "## Contribute" heading onwards.
//   - Rewrite relative links to absolute GitHub URLs on the default branch,
//     because shared files must not use relative links, and turn every link
//     into a reference link defined at the bottom of its own page.
//   - Refuse relative images, Hugo shortcode delimiters, and links that escape
//     the repository.
func Transform(readme []byte, sha string) ([]Page, error) {
	if err := validateSHA(sha); err != nil {
		return nil, err
	}
	if bytes.Contains(readme, []byte("{{")) || bytes.Contains(readme, []byte("{%")) {
		return nil, errors.New("README contains a Hugo shortcode delimiter; fix it in alloy-scenarios")
	}

	lines := strings.Split(strings.ReplaceAll(string(readme), "\r\n", "\n"), "\n")

	lines, err := trimTitle(lines)
	if err != nil {
		return nil, err
	}

	end := slices.Index(lines, endMarker)
	if end < 0 {
		return nil, fmt.Errorf("end marker %q not found; the README structure changed", endMarker)
	}
	lines = lines[:end]

	split := slices.Index(lines, scenariosMarker)
	if split < 0 {
		return nil, fmt.Errorf("heading %q not found; the README structure changed", scenariosMarker)
	}

	preamble, err := renderPage(preambleSlug, preambleTitle, lines[:split], sha, false)
	if err != nil {
		return nil, err
	}
	pages := []Page{{Slug: preambleSlug, Title: preambleTitle, Content: preamble}}

	categories, err := splitCategories(lines[split:])
	if err != nil {
		return nil, err
	}
	for _, c := range categories {
		content, err := renderPage(c.slug, c.title, c.body, sha, true)
		if err != nil {
			return nil, fmt.Errorf("category %q: %w", c.title, err)
		}
		pages = append(pages, Page{Slug: c.slug, Title: c.title, Content: content})
	}

	return pages, nil
}

// trimTitle drops the HTML banner and the H1, and returns the lines from the
// first H2 onwards.
func trimTitle(lines []string) ([]string, error) {
	i := skipBlank(lines, 0)
	if i < len(lines) && strings.HasPrefix(strings.TrimLeft(lines[i], " \t"), "<p") {
		for i < len(lines) && !strings.Contains(lines[i], "</p>") {
			i++
		}
		if i == len(lines) {
			return nil, errors.New("unterminated HTML banner block at the top of the README")
		}
		i++
	}

	i = skipBlank(lines, i)
	if i >= len(lines) || !strings.HasPrefix(lines[i], "# ") {
		return nil, errors.New("expected an H1 heading at the top of the README")
	}
	lines = lines[i+1:]

	start := slices.IndexFunc(lines, func(l string) bool { return strings.HasPrefix(l, "## ") })
	if start < 0 {
		return nil, errors.New("no H2 heading found after the H1 heading")
	}
	return lines[start:], nil
}

type category struct {
	slug  string
	title string
	body  []string
}

// splitCategories groups the lines under "## Scenarios" by category. Every
// category must be preceded by an alloy-docs slug marker, so that renaming a
// heading in alloy-scenarios can't silently repoint a documentation page.
func splitCategories(lines []string) ([]category, error) {
	var (
		out  []category
		seen = make(map[string]int)
		slug string
		cur  = -1
	)

	for i, line := range lines {
		trimmed := strings.TrimSpace(line)

		if m := markerRe.FindStringSubmatch(trimmed); m != nil {
			if slug != "" {
				return nil, fmt.Errorf("the marker for slug %q isn't followed by a category heading", slug)
			}
			slug = m[1]
			continue
		}
		if looseMarkerRe.MatchString(trimmed) {
			return nil, fmt.Errorf("malformed alloy-docs marker on line %d: %q", i+1, trimmed)
		}

		if strings.HasPrefix(line, "### ") {
			title := strings.TrimSpace(strings.TrimPrefix(line, "### "))
			if slug == "" {
				return nil, fmt.Errorf("category %q has no alloy-docs slug marker", title)
			}
			if prev, dup := seen[slug]; dup {
				return nil, fmt.Errorf("duplicate alloy-docs slug %q on categories %q and %q", slug, out[prev].title, title)
			}
			seen[slug] = len(out)
			out = append(out, category{slug: slug, title: title})
			cur = len(out) - 1
			slug = ""
			continue
		}

		if cur >= 0 {
			out[cur].body = append(out[cur].body, line)
		}
	}

	if slug != "" {
		return nil, fmt.Errorf("the marker for slug %q isn't followed by a category heading", slug)
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no scenario categories found under %q", scenariosMarker)
	}

	for i := range out {
		table, err := tableOf(out[i].body)
		if err != nil {
			return nil, fmt.Errorf("category %q: %w", out[i].title, err)
		}
		out[i].body = table
	}
	return out, nil
}

// tableOf returns the scenario table from a category body.
func tableOf(body []string) ([]string, error) {
	start := slices.IndexFunc(body, func(l string) bool { return strings.HasPrefix(l, "|") })
	if start < 0 {
		return nil, errors.New("no scenario table found")
	}

	end := start
	for end < len(body) && strings.HasPrefix(body[end], "|") {
		end++
	}

	// A header row, a delimiter row, and at least one scenario.
	if table := body[start:end]; len(table) >= 3 {
		return table, nil
	}
	return nil, errors.New("the scenario table has no rows")
}

func renderPage(slug, title string, body []string, sha string, withFooter bool) ([]byte, error) {
	links := &linkSet{}

	body, err := toReferenceLinks(trimBlankEnds(body), links)
	if err != nil {
		return nil, err
	}

	parts := []string{strings.Join(trimBlankEnds(body), "\n")}
	if withFooter {
		if err := links.add(repoLabel, repoURL); err != nil {
			return nil, err
		}
		parts = append(parts, footerLine)
	}
	if defs := links.definitions(); len(defs) > 0 {
		parts = append(parts, strings.Join(defs, "\n"))
	}

	header := fmt.Sprintf(headerFormat, slug, title, repoSlug, sha)
	return []byte(header + strings.Join(parts, "\n\n") + "\n"), nil
}

// linkSet collects reference-link definitions in order of first use.
//
// Definitions are gathered per page because the docs/shared shortcode renders
// each file through a separate Markdown parse, so a definition only resolves
// inside the file that declares it.
type linkSet struct {
	order []string
	dest  map[string]string
}

// normalizeLabel matches how Markdown compares reference labels: case-folded,
// with runs of whitespace collapsed.
func normalizeLabel(label string) string {
	return strings.ToLower(strings.Join(strings.Fields(label), " "))
}

func (s *linkSet) add(label, dest string) error {
	if strings.ContainsAny(label, "[]") || strings.TrimSpace(label) == "" {
		return fmt.Errorf("link text %q can't be used as a reference label", label)
	}

	key := normalizeLabel(label)
	if existing, ok := s.dest[key]; ok {
		if existing != dest {
			return fmt.Errorf("link text %q points at both %s and %s; make the link text unique in alloy-scenarios",
				label, existing, dest)
		}
		return nil
	}

	if s.dest == nil {
		s.dest = make(map[string]string)
	}
	s.dest[key] = dest
	s.order = append(s.order, label)
	return nil
}

func (s *linkSet) definitions() []string {
	defs := make([]string, 0, len(s.order))
	for _, label := range s.order {
		defs = append(defs, fmt.Sprintf("[%s]: %s", label, s.dest[normalizeLabel(label)]))
	}
	return defs
}

func validateSHA(sha string) error {
	if !shaRe.MatchString(sha) {
		return fmt.Errorf("invalid commit SHA %q: want 40 lowercase hex characters", sha)
	}
	return nil
}

func skipBlank(lines []string, i int) int {
	for i < len(lines) && strings.TrimSpace(lines[i]) == "" {
		i++
	}
	return i
}

func trimBlankEnds(lines []string) []string {
	for len(lines) > 0 && strings.TrimSpace(lines[0]) == "" {
		lines = lines[1:]
	}
	for len(lines) > 0 && strings.TrimSpace(lines[len(lines)-1]) == "" {
		lines = lines[:len(lines)-1]
	}
	return lines
}

// toReferenceLinks rewrites relative destinations and turns inline links into
// collapsed reference links, collecting their definitions in links. Fenced code
// blocks are left alone. Images stay inline, because a reference image would
// gain nothing and the generator refuses relative ones anyway.
func toReferenceLinks(lines []string, links *linkSet) ([]string, error) {
	out := make([]string, 0, len(lines))
	inFence := false

	for _, line := range lines {
		if strings.HasPrefix(strings.TrimLeft(line, " \t"), "```") {
			inFence = !inFence
			out = append(out, line)
			continue
		}
		if inFence {
			out = append(out, line)
			continue
		}

		// An existing definition is absorbed into the set and re-emitted with
		// the others, so every page ends with a single definition block.
		if d := defRe.FindStringSubmatch(line); d != nil {
			if strings.TrimSpace(d[3]) != "" {
				return nil, fmt.Errorf("link definition %q has a title, which isn't supported", line)
			}
			dest, err := rewriteDest(d[2])
			if err != nil {
				return nil, err
			}
			if err := links.add(d[1], dest); err != nil {
				return nil, err
			}
			continue
		}

		var firstErr error
		line = linkRe.ReplaceAllStringFunc(line, func(match string) string {
			sub := linkRe.FindStringSubmatch(match)
			bang, text, dest := sub[1], sub[2], sub[3]

			newDest, err := rewriteDest(dest)
			if err == nil && bang != "" && newDest != dest {
				err = fmt.Errorf("relative image %q is not supported", dest)
			}
			if err == nil && bang == "" {
				err = links.add(text, newDest)
			}
			if err != nil {
				if firstErr == nil {
					firstErr = err
				}
				return match
			}

			if bang != "" {
				return bang + "[" + text + "](" + newDest + ")"
			}
			return "[" + text + "][]"
		})
		if firstErr != nil {
			return nil, firstErr
		}

		out = append(out, line)
	}
	return out, nil
}

// rewriteDest turns a repository-relative destination into an absolute GitHub
// URL on the default branch. Destinations that already have a scheme, or that
// are anchors, site-absolute paths, or template expressions, are returned
// unchanged.
func rewriteDest(dest string) (string, error) {
	if schemeRe.MatchString(dest) ||
		strings.HasPrefix(dest, "#") ||
		strings.HasPrefix(dest, "/") ||
		strings.HasPrefix(dest, "{") {

		return dest, nil
	}

	fragment := ""
	if before, after, found := strings.Cut(dest, "#"); found {
		dest, fragment = before, "#"+after
	}

	path := strings.TrimPrefix(dest, "./")
	if path == "" || slices.Contains(strings.Split(path, "/"), "..") {
		return "", fmt.Errorf("cannot resolve relative link %q inside the repository", dest)
	}

	kind := "blob"
	if strings.HasSuffix(path, "/") {
		kind = "tree"
	}
	return fmt.Sprintf("https://github.com/%s/%s/%s/%s%s",
		repoSlug, kind, defaultBranch, strings.TrimRight(path, "/"), fragment), nil
}
