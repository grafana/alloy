//! Generates the Go side of every Rust component into
//! `<repo>/internal/component/<name with dots as slashes>/zz_generated.go`.
//!
//! Usage: alloy-gen <repo root>

use std::fmt::Write;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Duration;

use alloy_core::schema::{ComponentInfo, Field, FieldType, Kind, Stability, Value};

fn main() {
    let root = std::env::args()
        .nth(1)
        .expect("usage: alloy-gen <repo root>");

    let mut components: Vec<_> = alloy_ffi::registry().components().collect();
    components.sort_by_key(|c| c.name);

    for c in components {
        let path = write_component(Path::new(&root), c);
        let status = Command::new("gofmt")
            .arg("-w")
            .arg(&path)
            .status()
            .expect("run gofmt");
        assert!(status.success(), "gofmt failed for {}", path.display());
        println!("{}", path.display());
    }
}

fn write_component(root: &Path, c: &ComponentInfo) -> PathBuf {
    let dir = root
        .join("internal/component")
        .join(c.name.replace('.', "/"));
    std::fs::create_dir_all(&dir).expect("create package dir");

    let path = dir.join("zz_generated.go");
    std::fs::write(&path, generate(c)).expect("write zz_generated.go");
    path
}

fn generate(c: &ComponentInfo) -> String {
    let is_source = c.kind == Kind::Source;
    let register = match c.kind {
        Kind::Source => "RegisterLokiSource",
        Kind::Sink => "RegisterLokiSink",
    };
    let pkg = c.name.rsplit('.').next().unwrap();

    let checks: Vec<_> = c.args.iter().flat_map(checks).collect();
    let uses_time = c.args.iter().any(|f| f.ty == FieldType::Duration);

    let mut out = String::new();
    let w = &mut out;

    wl(w, "// Code generated by alloy-gen. DO NOT EDIT.");
    wl(w, "");
    wl(w, &format!("package {pkg}"));
    wl(w, "");
    wl(w, "import (");
    if !checks.is_empty() {
        wl(w, "\t\"errors\"");
    }
    if uses_time {
        wl(w, "\t\"time\"");
    }
    wl(w, "");
    wl(w, "\t\"github.com/grafana/alloy/internal/component/common/rustcomponent\"");
    wl(w, "\t\"github.com/grafana/alloy/internal/featuregate\"");
    wl(w, ")");
    wl(w, "");

    wl(w, "func init() {");
    wl(
        w,
        &format!(
            "\trustcomponent.{register}[Arguments]({:?}, featuregate.{})",
            c.name,
            stability(c.stability)
        ),
    );
    wl(w, "}");
    wl(w, "");

    wl(w, &format!("// Arguments holds values which are used to configure the {} component.", c.name));
    wl(w, "type Arguments struct {");
    if is_source {
        wl(w, "\tSource rustcomponent.LokiSourceArguments `alloy:\",squash\" cbor:\"-\"`");
    }
    for (i, f) in c.args.iter().enumerate() {
        if is_source || i > 0 {
            wl(w, "");
        }
        wl(w, &format!("\t// {}", f.doc));
        let optional = if f.default.is_some() { ",optional" } else { "" };
        wl(
            w,
            &format!(
                "\t{} {} `alloy:\"{},attr{optional}\" cbor:\"{}\"`",
                go_name(f.name),
                go_type(f.ty),
                f.name,
                f.name
            ),
        );
    }
    wl(w, "}");
    wl(w, "");

    wl(w, "var DefaultArguments = Arguments{");
    for f in c.args {
        if let Some(v) = f.default {
            wl(w, &format!("\t{}: {},", go_name(f.name), go_value(v)));
        }
    }
    wl(w, "}");
    wl(w, "");

    wl(w, "// SetToDefault implements syntax.Defaulter.");
    wl(w, "func (a *Arguments) SetToDefault() {");
    wl(w, "\t*a = DefaultArguments");
    wl(w, "}");
    wl(w, "");

    wl(w, "// Validate implements syntax.Validator.");
    wl(w, "func (a *Arguments) Validate() error {");
    for check in &checks {
        w.push_str(check);
    }
    wl(w, "\treturn nil");
    wl(w, "}");

    if is_source {
        wl(w, "");
        wl(w, "func (a Arguments) LokiSource() rustcomponent.LokiSourceArguments {");
        wl(w, "\treturn a.Source");
        wl(w, "}");
    }

    out
}

fn wl(w: &mut String, line: &str) {
    writeln!(w, "{line}").unwrap();
}

/// Bounds checks for a field: the schema's min/max, otherwise the range of
/// its Rust type where a Go int can exceed it.
fn checks(f: &Field) -> Vec<String> {
    let (type_min, type_max) = type_range(f.ty);
    let min = f.min.or(type_min);
    let max = f.max.or(type_max);

    let name = go_name(f.name);
    let mut out = Vec::new();
    if let Some(v) = min {
        out.push(format!(
            "\tif a.{name} < {} {{\n\t\treturn errors.New(\"{} must be at least {}\")\n\t}}\n",
            go_value(v),
            f.name,
            display(v)
        ));
    }
    if let Some(v) = max {
        out.push(format!(
            "\tif a.{name} > {} {{\n\t\treturn errors.New(\"{} must be at most {}\")\n\t}}\n",
            go_value(v),
            f.name,
            display(v)
        ));
    }
    out
}

fn type_range(ty: FieldType) -> (Option<Value>, Option<Value>) {
    use FieldType::*;
    let uint = |max: u64| (Some(Value::Uint(0)), Some(Value::Uint(max)));
    let int = |bits: u32| {
        let max = (1i64 << (bits - 1)) - 1;
        (Some(Value::Int(-max - 1)), Some(Value::Int(max)))
    };
    match ty {
        U8 => uint(u8::MAX as u64),
        U16 => uint(u16::MAX as u64),
        U32 => uint(u32::MAX as u64),
        // A Go int can't exceed these.
        U64 => (Some(Value::Uint(0)), None),
        I8 => int(8),
        I16 => int(16),
        I32 => int(32),
        I64 | F32 | F64 | Bool | String | StringMap => (None, None),
        Duration => (Some(Value::Duration(std::time::Duration::ZERO)), None),
    }
}

fn go_name(name: &str) -> String {
    name.split('_')
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().chain(chars).collect(),
                None => String::new(),
            }
        })
        .collect()
}

fn go_type(ty: FieldType) -> &'static str {
    use FieldType::*;
    match ty {
        U8 | U16 | U32 | U64 | I8 | I16 | I32 | I64 => "int",
        F32 | F64 => "float64",
        Bool => "bool",
        Duration => "time.Duration",
        String => "string",
        StringMap => "map[string]string",
    }
}

fn go_value(v: Value) -> String {
    match v {
        Value::Uint(n) => n.to_string(),
        Value::Int(n) => n.to_string(),
        Value::Float(f) => format!("{f:?}"),
        Value::Bool(b) => b.to_string(),
        Value::Duration(d) => go_duration(d),
        Value::Str(s) => go_string(s),
    }
}

fn go_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c if c.is_control() => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn go_duration(d: Duration) -> String {
    let ns = d.as_nanos();
    if ns == 0 {
        return "0".to_string();
    }
    const UNITS: [(u128, &str); 6] = [
        (3_600_000_000_000, "Hour"),
        (60_000_000_000, "Minute"),
        (1_000_000_000, "Second"),
        (1_000_000, "Millisecond"),
        (1_000, "Microsecond"),
        (1, "Nanosecond"),
    ];
    let (unit, name) = UNITS.iter().find(|(unit, _)| ns.is_multiple_of(*unit)).unwrap();
    format!("{} * time.{name}", ns / unit)
}

fn display(v: Value) -> String {
    match v {
        Value::Duration(d) => format!("{d:?}"),
        v => go_value(v),
    }
}

fn stability(s: Stability) -> &'static str {
    match s {
        Stability::Experimental => "StabilityExperimental",
        Stability::PublicPreview => "StabilityPublicPreview",
        Stability::GenerallyAvailable => "StabilityGenerallyAvailable",
    }
}
